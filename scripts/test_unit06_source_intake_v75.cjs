'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const load=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const m=load('quality/grade11-unit06-v75-source-intake.json');
assert.equal(m.unit,6);
assert.equal(m.publicationStatus,'source-inventory-only');
assert.equal(m.source.compiledPdfPages,577);
assert.equal(m.topics.length,7);
assert.equal(m.preparedTopicMcqsPerTopic,80);
assert.equal(m.preparedTopicMcqsNominalTotal,7*80);
assert.equal(m.textbookExercise.mcqs.count,14);
assert.equal(m.textbookExercise.shortQuestions.count,11);
assert.equal(m.textbookExercise.comprehensiveQuestions.count,11);
assert.equal(m.textbookExercise.numericals.count,11);
assert.deepEqual(m.topics.map(t=>t.pdfStarts.mcqs),[3,51,99,137,183,227,274]);
assert.deepEqual(m.topics.map(t=>t.pdfStarts.examples),[40,88,127,173,220,266,304]);
const allStarts=m.topics.flatMap(t=>Object.values(t.pdfStarts));
assert.ok(allStarts.every((v,i)=>Number.isInteger(v)&&v>0&&(i===0||v>allStarts[i-1])),'PDF section pages must be increasing');
assert.deepEqual(Object.values(m.textbookExercise).map(x=>x.startPdfPage),[312,315,319,330]);
const simulations=load('portal/simulation-catalog.json').simulations.filter(s=>s.unit===6&&!s.additional);
assert.equal(simulations.length,5);
assert.deepEqual(simulations.map(s=>s.file).sort(),m.existingPublicSimulations.slice().sort());
for(const file of m.existingPublicSimulations)assert.ok(fs.existsSync(path.join(root,file)),file+' missing');
const videos=load('portal/hssc-concept-videos-v74.json').videos.filter(v=>v.unit===6);
assert.equal(videos.length,1);
assert.equal(videos[0].videoId,m.directYouTubeVideoId);
const grade=load('portal/learning-catalog.json').grades.find(g=>g.grade===11);
const u6=grade.units.find(u=>u.unit===6);
assert.equal(u6.status,'planned');
assert.equal(u6.questionBankCount,0);
assert.equal(u6.simulationCount,5);
assert.equal(u6.directYouTubeCount,1);
assert.equal(grade.units.filter(u=>u.status==='available').reduce((n,u)=>n+u.questionBankCount,0),1690);
assert.ok(!fs.existsSync(path.join(root,'portal','Grade11_Unit6_COMPLETE_MASTER_ALL.pdf')),'Do not expose library master PDF in public portal');
assert.ok(!fs.existsSync(path.join(root,'portal','unit-06.html')),'Do not accidentally advertise a completed Unit6');
assert.equal(m.readiness.publicQuestionBankCount,0);
console.log('V75 PASS: Unit6 source inventory and public-content boundaries verified; actual 577-page source remains outside GitHub.');
