/* Physics with Sir Najam — Unit 4 Part 3 rotating-station lab UI.
 * Schematic visuals; model numbers from physics source module at actual rpm.
 * Animation intentionally time-scaled and capped for class visibility.
 * No external network, saved accounts, grades or storage.
 */
(function(){
"use strict";
const model=window.PSNUnit4ArtificialGravity;
if(!model)return;
const $=id=>document.getElementById(id);
let angle=0.23,frame=null,last=null,playing=false;
const fmt=(n,dp=2)=>model.format(n,dp);
const values=()=>({
 radius:Number($("stationRadius").value),
 rpm:Number($("stationRPM").value),
 mass:Number($("personMass").value)
});
function updateStationSvg(){
 const p={x:247+111*Math.cos(angle),y:178-111*Math.sin(angle)};
 $("rotatingGroup").setAttribute("transform","rotate("+(-angle*180/Math.PI)+" 247 178)");
 const fx=247-p.x,fy=178-p.y,dist=Math.hypot(fx,fy);
 const unitX=fx/dist,unitY=fy/dist;
 const arrow=$("floorNormalArrow");
 for(const [attr,value] of Object.entries({x1:p.x,y1:p.y,x2:p.x+unitX*74,y2:p.y+unitY*74}))
   arrow.setAttribute(attr,String(value));
 $("normalLabel").setAttribute("x",String(p.x+unitX*92));
 $("normalLabel").setAttribute("y",String(p.y+unitY*92-10));
 const data=values();
 arrow.style.visibility=data.rpm===0?"hidden":"visible";
 $("normalLabel").textContent=data.rpm===0?
  "No rotation: N = 0":"Real floor normal (inward)";
 $("ringPlot").setAttribute("aria-label","Ring viewed along its axis. The occupant sits on the outer rim. "+
  (data.rpm===0?"At rest, the ideal rotating-gravity floor normal is zero.":
   "An inward floor normal force points from the occupant toward the axis; the numeric acceleration uses the selected actual rotation rate."));
}
function update(){
 const {radius,rpm,mass}=values();
 const p=model.calculate(radius,rpm,mass);
 $("stationRadiusValue").textContent=fmt(radius,2)+" m";
 $("stationRPMValue").textContent=fmt(rpm,4)+" rpm";
 $("personMassValue").textContent=fmt(mass,0)+" kg";
 $("artificialAcceleration").textContent=fmt(p.centripetalAcceleration,3)+" m/s²";
 $("gRatio").textContent=fmt(p.effectiveGravityRatio,3)+" g";
 $("omega").textContent=fmt(p.omegaRadPerSec,4)+" rad/s";
 $("rimSpeed").textContent=fmt(p.rimSpeedMetresPerSec,3)+" m/s";
 $("period").textContent=p.periodSeconds===null?"Not rotating":fmt(p.periodSeconds,2)+" s";
 $("frequency").textContent=fmt(p.frequencyHz,4)+" Hz";
 $("normalForce").textContent=fmt(p.floorNormalNewtons,2)+" N";
 $("gravityFill").style.width=Math.min(100,p.effectiveGravityRatio/2*100)+"%";
 $("gravityBar").setAttribute("aria-label","Artificial acceleration is "+fmt(p.effectiveGravityRatio,3)+
  " times reference Earth gravity 9.8 metres per second squared; bar is capped at 2g.");
 if(rpm===0){
  $("stationStatus").textContent="Station is not rotating: ideal rim acceleration, floor normal and artificial gravity are all zero. The period is undefined.";
  $("gravityExplanation").textContent="At zero rpm, no artificial gravity is generated by rotation. In the model no external gravity is acting.";
 }else{
  $("stationStatus").textContent="Rim radius "+fmt(radius,1)+" m; "+
   fmt(rpm,3)+" revolutions/minute. The floor normal acts toward the axis: N = mω²R = "+
   fmt(p.floorNormalNewtons,1)+" N for the selected person mass.";
  $("gravityExplanation").textContent="The floor's inward normal force gives "+
   fmt(p.centripetalAcceleration,3)+" m/s² at the rim, about "+
   fmt(p.effectiveGravityRatio,3)+" g. The outward apparent weight belongs to the rotating frame; the animation is time-scaled.";
 }
 updateStationSvg();
}
function stop(){
 if(frame!==null)cancelAnimationFrame(frame);
 frame=null;last=null;playing=false;$("spin").textContent="Play station rotation";
}
function animate(timestamp){
 if(!playing)return;
 if(last===null)last=timestamp;
 const dt=Math.min(.08,Math.max(0,(timestamp-last)/1000));last=timestamp;
 const omega=model.calculate(values().radius,values().rpm,values().mass).omegaRadPerSec;
 // For projector legibility: show scaled motion; never use it in physics calculations.
 const displayRate=omega===0?0:Math.min(1.6,10*omega);
 angle=(angle+displayRate*dt)%(2*Math.PI);
 updateStationSvg();
 frame=requestAnimationFrame(animate);
}
function setParameters(radius,rpm,mass){
 stop();$("stationRadius").value=String(radius);
 $("stationRPM").value=String(rpm);
 $("personMass").value=String(mass);
 angle=.23;update();
}
function preset(which){
 if(which==="example44"){
  const ex=model.textbook44().calculated;
  setParameters(ex.radiusMetres,ex.rpm,70);
 }else if(which==="assignment44"){
  const ex=model.assignment44().calculated;
  setParameters(ex.radiusMetres,ex.rpm,70);
 }else if(which==="small"){
  const ex=model.designForGravity(4);
  setParameters(ex.radiusMetres,ex.rpm,70);
 }
}
for(const id of ["stationRadius","stationRPM","personMass"])
 $(id).addEventListener("input",()=>{stop();update();});
for(const b of document.querySelectorAll("[data-preset]"))
 b.addEventListener("click",()=>preset(b.dataset.preset));
$("earthTarget").addEventListener("click",()=>{
 const {radius,mass}=values();
 const ex=model.designForGravity(radius,model.STANDARD_G,mass);
 setParameters(ex.radiusMetres,ex.rpm,ex.personMassKg);
});
$("spin").addEventListener("click",()=>{
 if(playing){stop();return;}
 playing=true;last=null;$("spin").textContent="Pause station rotation";
 frame=requestAnimationFrame(animate);
});
$("resetSpin").addEventListener("click",()=>{
 stop();angle=.23;updateStationSvg();
});
document.addEventListener("visibilitychange",()=>{if(document.hidden)stop();});
preset("example44");
})();